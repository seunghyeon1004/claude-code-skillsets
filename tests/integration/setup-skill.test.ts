    const rootEntries = await readdir(
      join(projectRoot, "tests", "evaluations", "skillset-manager"),
      { withFileTypes: true }
    );
    expect(rootEntries.filter((entry) => entry.isFile()).map((entry) => entry.name)).toEqual([]);
