describe("decision setup evaluation corpus", () => {
  it("replaces legacy selection scenarios with the complete decision journey", async () => {
    const rootEntries = await readdir(
      join(projectRoot, "tests", "evaluations", "skillset-manager"),
      { withFileTypes: true }
    );
    expect(rootEntries.filter((entry) => entry.isFile()).map((entry) => entry.name)).toEqual([]);
    expect(
      rootEntries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()
    ).toEqual(["doctor", "maintain", "setup"]);

    const entries = (await readdir(evaluationsRoot, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && entry.name.endsWith(".yaml"))
      .map((entry) => entry.name)
      .sort();
    expect(entries).toEqual([
      "01-setup-research-evidence-ko.yaml",
      "02-setup-video-editing.yaml",
      "03-setup-ambiguous-indexed-tie.yaml",
      "04-setup-two-domains-current-approval.yaml",
      "05-setup-three-domain-reprioritization.yaml",
      "06-setup-expired-catalog.yaml",
      "07-setup-current-approval-no-execution.yaml",
      "08-setup-refused-time-probe.yaml",
      "09-setup-changed-digest-old-approval.yaml"
    ]);

    const loaded = await Promise.all(entries.map(async (file) => {
      const value = YAML.parse(await readFile(join(evaluationsRoot, file), "utf8")) as Record<string, unknown>;
      expect(Object.keys(value)).toEqual(["id", "caseType", "prompt", "expectedBehaviors", "forbiddenBehaviors"]);
      expect(value.id).toBe(scenarioIds[entries.indexOf(file)]);
      expect(value.prompt).not.toMatch(/Essential|Recommended|Custom Max|install-index/i);
      expect(value.expectedBehaviors).toEqual(expect.any(Array));
      expect(value.forbiddenBehaviors).toEqual(expect.any(Array));
      return value;
    }));
    expect(loaded).toHaveLength(9);
    expect(loaded.every((value) => (value.expectedBehaviors as unknown[]).length > 0)).toBe(true);
    expect(loaded.every((value) => (value.forbiddenBehaviors as unknown[]).length > 0)).toBe(true);
  });

  it("keeps scenario state in a non-authoritative manifest and reads recommendations from the plugin index", async () => {
    const manifest = validateSetupDecisionScenarioManifest(YAML.parse(
      await readFile(join(fixturesRoot, "decision-scenarios.yaml"), "utf8")
    ) as unknown);
    const cases = await loadSetupCases();

    expect(manifest).toMatchObject({ schemaVersion: 1, recommendationData: "plugin-owned-decision-index" });
    expect(manifest.scenarios.map(({ id }) => id)).toEqual(scenarioIds);
    expect(manifest.scenarios.every(({ input, expected }) =>
      Object.keys(input).length > 0 && expected.state.length > 0
    )).toBe(true);
    expect(cases.map(({ id }) => id)).toEqual(scenarioIds);
    expect(cases.every(({ fixturePluginRoot }) => fixturePluginRoot === pluginRoot)).toBe(true);
  });
});

function section(content: string, start: string, end?: string): string {
  const startIndex = content.indexOf(start);
  expect(startIndex, `missing ${start}`).toBeGreaterThanOrEqual(0);
  const endIndex = end === undefined ? content.length : content.indexOf(end, startIndex + start.length);
  expect(endIndex, `missing ${end ?? "<end>"}`).toBeGreaterThan(startIndex);
  return content.slice(startIndex, endIndex);
}

function expectOrdered(content: string, markers: string[]): void {
  let previousIndex = -1;
  for (const marker of markers) {
    const index = content.indexOf(marker);
    expect(index, `missing ${marker}`).toBeGreaterThan(previousIndex);
    previousIndex = index;
  }
}
