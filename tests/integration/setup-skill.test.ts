function section(content: string, start: string, end?: string): string {
  const startIndex = content.indexOf(start);
  expect(startIndex, `missing ${start}`).toBeGreaterThanOrEqual(0);
  const endIndex = end === undefined ? content.length : content.indexOf(end, startIndex + start.length);
  expect(endIndex, `missing ${end ?? "<end>"}`).toBeGreaterThan(startIndex);
  return content.slice(startIndex, endIndex);
}

function expectOrdered(content: string, markers: string[]): void {
  let previousIndex = -1;
  for (const marker of markers) {
    const index = content.indexOf(marker);
    expect(index, `missing ${marker}`).toBeGreaterThan(previousIndex);
    previousIndex = index;
  }
}
